import SwiftUI
import FoundationModels

struct TravelTipView: View {
    let viewModel: LocationDetailViewModel
    let city: String
    let temperature: Int
    let condition: String
    var body: some View {
        VStack(alignment: .leading, spacing: 16) {
            HStack {
                Text("AI Travel Tips")
                    .font(.title2)
                    .fontWeight(.bold)
                Spacer()
                Text("Foundation Models")
                    .font(.caption)
                    .foregroundStyle(.purple)
                    .fontWeight(.medium)
            }
            VStack(alignment: .leading, spacing: 12) {
                if viewModel.isGenerating {
                    loadingView
                } else if let error = viewModel.errorMessage {
                    errorView(message: error)
                } else if let tip = viewModel.travelTip {
                    tipContentView(tip: tip)
                } else {
                    ProgressView().frame(maxWidth: .infinity)
                }
            }
            .padding()
            .background(.regularMaterial)
            .clipShape(RoundedRectangle(cornerRadius: 16))
        }
    }
    private var loadingView: some View {
        VStack(spacing: 8) {
            ProgressView().controlSize(.regular)
            Text("Generating...")
                .font(.caption).foregroundStyle(.secondary)
        }
        .frame(maxWidth: .infinity)
        .padding(.vertical, 12)
    }
    private func errorView(message: String) -> some View {
        VStack(spacing: 12) {
            Image(systemName: "exclamationmark.triangle")
                .font(.title2).foregroundStyle(.orange)
            Text(message)
                .font(.subheadline).foregroundStyle(.secondary)
                .multilineTextAlignment(.center)
            Button("Retry") {
                Task {
                    await viewModel.retry(
                        city: city, temperature: temperature, condition: condition
                    )
                }
            }
            .buttonStyle(.borderedProminent)
        }
        .frame(maxWidth: .infinity).padding(.vertical, 8)
    }
    private func tipContentView(tip: TravelTip) -> some View {
        VStack(alignment: .leading, spacing: 12) {
            if viewModel.wasGeneratedByAI {
                Text("Generated by on-device AI")
                    .font(.caption).foregroundStyle(.purple).fontWeight(.medium)
                    .frame(maxWidth: .infinity, alignment: .center)
                Divider()
            }
            tipRow(title: "Travel Tip", value: tip.tip)
            Divider()
            tipRow(title: "What to Pack", value: tip.packingItem)
            Divider()
            tipRow(title: "Local Food", value: tip.localFood)
        }
    }
    private func tipRow(title: String, value: String) -> some View {
        VStack(alignment: .leading, spacing: 4) {
            Text(title).font(.subheadline).fontWeight(.bold)
            Text(value).font(.subheadline).foregroundStyle(.primary)
        }
    }
}
