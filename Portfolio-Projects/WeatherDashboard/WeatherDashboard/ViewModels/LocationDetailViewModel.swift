import Foundation
import FoundationModels
import Observation

@Observable
class LocationDetailViewModel {

    var travelTip: TravelTip?
    var isGenerating: Bool = false
    var errorMessage: String?
    var isAvailable: Bool = SystemLanguageModel.default.isAvailable
    var wasGeneratedByAI: Bool = false

    private var session: LanguageModelSession?

    private func makeSession() -> LanguageModelSession {
        LanguageModelSession(
            instructions: """
            You are a helpful travel assistant.
            Provide brief, practical travel advice based on
            the city and weather conditions provided.
            Keep tips concise and actionable.
            """
        )
    }

    func generateTip(city: String, temperature: Int, condition: String) async {

        guard isAvailable else {
            travelTip = TravelTip.fallback(for: city)
            return
        }

        isGenerating = true
        errorMessage = nil

        if session == nil {
            session = makeSession()
        }

        let prompt = "Travel tip for \(city), \(temperature)°F, \(condition)"

        do {
            let response = try await session!.respond(
                to: prompt,
                generating: TravelTip.self
            )
            travelTip = response.content
            wasGeneratedByAI = true   // tip was genuinely generated by AI

        } catch {
            // On simulator, model assets may not be available
            // Show fallback tips instead of error
            travelTip = TravelTip.fallback(for: city)
            wasGeneratedByAI = false
            session = nil
        }

        isGenerating = false
    }

    func retry(city: String, temperature: Int, condition: String) async {
        travelTip = nil
        errorMessage = nil
        await generateTip(
            city: city,
            temperature: temperature,
            condition: condition
        )
    }
}
